const STORAGE_KEY = "lexisprig-lang";

function detectInitialLang() {
  try {
    const params = new URLSearchParams(window.location.search);
    const queryLang = params.get("lang");
    if (queryLang === "zh" || queryLang === "zh-Hans") return "zh";
    if (queryLang === "en") return "en";

    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "zh" || saved === "en") return saved;
  } catch (_) {
    // Ignore storage access errors in restricted environments
  }

  const navLangs = Array.isArray(navigator.languages) && navigator.languages.length > 0
    ? navigator.languages
    : [navigator.language || "en"];

  for (const candidate of navLangs) {
    if (typeof candidate === "string" && candidate.toLowerCase().startsWith("zh")) {
      return "zh";
    }
    if (typeof candidate === "string" && candidate.toLowerCase().startsWith("en")) {
      return "en";
    }
  }
  return "zh";
}

let currentLang = detectInitialLang();

function resolveKey(obj, path) {
  return path.split(".").reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : null), obj);
}

function applyLanguage(lang, persist = false) {
  currentLang = lang === "en" ? "en" : "zh";

  if (persist) {
    try {
      window.localStorage.setItem(STORAGE_KEY, currentLang);
    } catch (_) {
      // Ignore storage errors
    }
  }

  // Constraint 2: Synchronize both standard lang attribute and data-lang for separated CSS styling
  document.documentElement.lang = currentLang === "zh" ? "zh-Hans" : "en";
  document.documentElement.dataset.lang = currentLang;

  // Apply text translations
  const dict = translations[currentLang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = resolveKey(dict, key);
    if (value !== null) {
      el.innerHTML = value;
    }
  });

  // Update page title and meta description
  const pageKey = document.body.dataset.page || "home";
  const meta = (pageMeta[pageKey] && pageMeta[pageKey][currentLang]) || pageMeta.home[currentLang];
  if (meta) {
    document.title = meta.title;
    const descEl = document.querySelector('meta[name="description"]');
    if (descEl) descEl.setAttribute("content", meta.description);
    const ogTitle = document.querySelector('meta[property="og:title"]');
    if (ogTitle) ogTitle.setAttribute("content", meta.title);
    const ogDesc = document.querySelector('meta[property="og:description"]');
    if (ogDesc) ogDesc.setAttribute("content", meta.description);
  }

  // Update language switcher buttons active state
  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    const target = btn.getAttribute("data-set-lang");
    const isActive = target === currentLang;
    btn.classList.toggle("is-active", isActive);
    btn.setAttribute("aria-pressed", isActive ? "true" : "false");
  });

  // Keep screenshot slots visibly pending until genuine current-app captures replace them.
  document.querySelectorAll("[data-screenshot]").forEach((slot) => {
    const slotNum = Number(slot.getAttribute("data-screenshot"));
    const label = screenshotAlts[currentLang]?.[slotNum];
    if (label) {
      slot.textContent = label;
      slot.setAttribute("aria-label", label);
    }
  });

  // Update hamburger button aria-label
  const navToggle = document.getElementById("nav-toggle");
  if (navToggle) {
    const isExpanded = navToggle.getAttribute("aria-expanded") === "true";
    navToggle.setAttribute("aria-label", isExpanded ? dict.nav.closeMenu : dict.nav.openMenu);
  }
}

function setupNavigation() {
  const navToggle = document.getElementById("nav-toggle");
  const navMenu = document.getElementById("site-nav-menu");

  function setMenuOpen(open) {
    if (!navToggle || !navMenu) return;
    navToggle.setAttribute("aria-expanded", open ? "true" : "false");
    navMenu.classList.toggle("is-open", open);
    const dict = translations[currentLang];
    navToggle.setAttribute("aria-label", open ? dict.nav.closeMenu : dict.nav.openMenu);
  }

  if (navToggle && navMenu) {
    navToggle.addEventListener("click", () => {
      const isExpanded = navToggle.getAttribute("aria-expanded") === "true";
      setMenuOpen(!isExpanded);
    });

    navMenu.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", () => setMenuOpen(false));
    });

    document.addEventListener("keydown", (event) => {
      if (event.key === "Escape" && navToggle.getAttribute("aria-expanded") === "true") {
        setMenuOpen(false);
        navToggle.focus();
      }
    });

    window.addEventListener("resize", () => {
      if (window.innerWidth > 860 && navToggle.getAttribute("aria-expanded") === "true") {
        setMenuOpen(false);
      }
    });
  }

  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    btn.addEventListener("click", () => {
      const target = btn.getAttribute("data-set-lang");
      applyLanguage(target, true);
    });
  });
}

document.addEventListener("DOMContentLoaded", () => {
  setupNavigation();
  applyLanguage(currentLang, false);
});
